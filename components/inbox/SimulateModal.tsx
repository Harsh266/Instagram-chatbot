"use client";

import { Copy, Send } from "lucide-react";
import { useState } from "react";
import { actions, type IncomingResult } from "@/lib/store";
import type { Workspace } from "@/lib/types";
import { Modal } from "../ui/Modal";
import { Button, DemoNotice, Field, Input, Select, Textarea } from "../ui/primitives";
import { toast } from "../ui/toast";

export const SCENARIOS = [
  { id: "price", label: "Asking about service prices", text: "Hi, what is your website development price?" },
  { id: "availability", label: "Asking about product availability", text: "Is the e-commerce website service available right now?" },
  { id: "discount", label: "Asking for a discount", text: "Do you offer any discount?" },
  { id: "delivery", label: "Asking about delivery", text: "How long does delivery take?" },
  { id: "purchase", label: "Expressing interest in purchasing", text: "I want to book the Instagram chatbot setup for my store." },
  { id: "budget", label: "Providing a budget", text: "My budget is ₹30,000 and I need it this month. I'm based in Pune." },
  { id: "unknown", label: "Question the knowledge base can't answer", text: "Do you also provide CCTV installation?" },
  { id: "human", label: "Requesting a human representative", text: "Can I talk to a real person please?" },
  { id: "optout", label: "Opting out of messages", text: "Please stop messaging me, not interested." },
] as const;

const NEW = "__new__";

export function SimulateModal({
  ws,
  open,
  onClose,
  defaultCustomerId,
  onSent,
}: {
  ws: Workspace;
  open: boolean;
  onClose: () => void;
  defaultCustomerId: string | null;
  onSent: (conversationId: string) => void;
}) {
  return open ? <Inner ws={ws} onClose={onClose} defaultCustomerId={defaultCustomerId} onSent={onSent} /> : null;
}

function Inner({ ws, onClose, defaultCustomerId, onSent }: { ws: Workspace; onClose: () => void; defaultCustomerId: string | null; onSent: (id: string) => void }) {
  const [customerId, setCustomerId] = useState(defaultCustomerId ?? ws.customers[0]?.id ?? NEW);
  const [scenario, setScenario] = useState<string>(SCENARIOS[0].id);
  const [text, setText] = useState<string>(SCENARIOS[0].text);
  const [newName, setNewName] = useState("");
  const [newUser, setNewUser] = useState("");
  const [errors, setErrors] = useState<Record<string, string>>({});
  const connected = ws.instagram.status === "connected";

  const conv = ws.conversations.find((c) => c.customerId === customerId);
  const lastIn = conv ? ws.messages.findLast((m) => m.conversationId === conv.id && m.sender === "customer") : undefined;

  const report = (r: IncomingResult) => {
    if (!r.ok) return toast(r.message, "error");
    toast(r.message, r.status === "duplicate" ? "info" : "success");
    if (r.conversationId) onSent(r.conversationId);
    onClose();
  };

  const submit = () => {
    const e: Record<string, string> = {};
    if (!text.trim()) e.text = "Enter the customer's message.";
    if (customerId === NEW) {
      if (newName.trim().length < 2) e.name = "Enter the sample customer's name.";
      if (!/^@?[a-z0-9._]{3,30}$/i.test(newUser.trim())) e.user = "Use 3–30 letters, numbers, dots or underscores.";
      else if (ws.customers.some((c) => c.username.toLowerCase() === newUser.trim().replace(/^@/, "").toLowerCase())) e.user = "That username already exists.";
    }
    setErrors(e);
    if (Object.keys(e).length) return;
    report(
      actions.simulateIncoming(
        customerId === NEW ? { newCustomer: { name: newName, username: newUser }, text } : { customerId, text },
      ),
    );
  };

  return (
    <Modal
      open
      onClose={onClose}
      title="Simulate Customer Message"
      description="Workflow stage 2 — pretend a customer sent an Instagram DM."
      footer={
        <>
          {lastIn && customerId !== NEW && (
            <Button
              variant="ghost"
              icon={Copy}
              onClick={() => report(actions.simulateIncoming({ customerId, text: lastIn.text, externalId: lastIn.externalId }))}
              title="Deliver the last message again with the same Instagram message ID"
            >
              Re-deliver last message
            </Button>
          )}
          <Button variant="outline" onClick={onClose}>
            Cancel
          </Button>
          <Button icon={Send} onClick={submit} disabled={!connected}>
            Send simulated message
          </Button>
        </>
      }
    >
      <div className="space-y-4">
        <DemoNotice>No real Instagram message is received. The reply is generated by the local demo rules using your approved business information.</DemoNotice>
        {!connected && (
          <p className="rounded-lg border border-red-200 bg-red-50 p-3 text-xs text-red-700" role="alert">
            The demo Instagram account is disconnected. Connect it in Business Setup → Instagram Connection to simulate messages.
          </p>
        )}
        <Field label="Sample customer" htmlFor="sim-c">
          <Select id="sim-c" value={customerId} onChange={(e) => setCustomerId(e.target.value)}>
            {ws.customers.map((c) => (
              <option key={c.id} value={c.id}>
                {c.name} (@{c.username})
              </option>
            ))}
            <option value={NEW}>+ New sample customer</option>
          </Select>
        </Field>
        {customerId === NEW && (
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
            <Field label="Name" htmlFor="sim-n" required error={errors.name}>
              <Input id="sim-n" value={newName} onChange={(e) => setNewName(e.target.value)} aria-invalid={Boolean(errors.name)} placeholder="Riya Patel" />
            </Field>
            <Field label="Instagram username" htmlFor="sim-u" required error={errors.user}>
              <Input id="sim-u" value={newUser} onChange={(e) => setNewUser(e.target.value)} aria-invalid={Boolean(errors.user)} placeholder="@riya.creates" />
            </Field>
          </div>
        )}
        <Field label="Message scenario" htmlFor="sim-s">
          <Select
            id="sim-s"
            value={scenario}
            onChange={(e) => {
              setScenario(e.target.value);
              const s = SCENARIOS.find((x) => x.id === e.target.value);
              if (s) setText(s.text);
            }}
          >
            {SCENARIOS.map((s, i) => (
              <option key={s.id} value={s.id}>
                {i + 1}. {s.label}
              </option>
            ))}
            <option value="custom">Custom message</option>
          </Select>
        </Field>
        <Field label="Customer message" htmlFor="sim-t" required error={errors.text} hint="Edit freely — this is exactly what the simulated customer sends.">
          <Textarea
            id="sim-t"
            value={text}
            onChange={(e) => {
              setText(e.target.value);
              if (!SCENARIOS.some((s) => s.text === e.target.value)) setScenario("custom");
            }}
            aria-invalid={Boolean(errors.text)}
          />
        </Field>
        {conv?.botPaused && <p className="text-xs text-amber-700">The chatbot is paused for this conversation, so no automatic reply will be generated.</p>}
      </div>
    </Modal>
  );
}
